#!/usr/bin/env bash
# Phase 11: fail the build on any copyleft (GPL/AGPL/LGPL) dependency.
#
# Phase 15: this used to run `uv run pip-licenses > THIRD_PARTY_LICENSES.md`
# unconditionally. On a machine without `uv` (the HP ZGX Nano, which runs this
# project out of the shared `zgx` conda env) that redirect truncated the tracked
# licenses file to nothing, and the final `if uv run ... | grep -Ei 'GPL'` then
# matched nothing and printed "License audit OK" -- a licensing gate reporting a
# pass while auditing zero packages. Now: resolve a runner explicitly, refuse to
# run without one, and never write the output file until the tool has succeeded.
set -uo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

# Some machines (this one included) have a system-wide PYTHONPATH set for
# unrelated tooling (here: ROCm's amd_smi, from Jerome's existing GPU setup).
# That leaks into pip-licenses' import scan despite uv's venv isolation and
# reports packages that were never actually added to this project. Clear it
# so the audit reflects only this project's real dependency tree.
unset PYTHONPATH

# This audit requires `uv`, and deliberately has no fallback. pip-licenses reports
# whatever is installed in the environment it runs under, so it is only meaningful
# in an environment scoped to THIS project -- which is exactly what `uv run` gives
# and what a shared env does not. Running it under the ZGX Nano's shared `zgx`
# conda env would emit a THIRD_PARTY_LICENSES.md listing several hundred unrelated
# packages (torch, azure, anthropic, the TensorRT demos' deps) as if they were this
# project's dependencies -- worse than no file at all for a compliance artifact.
#
# So: run this on a machine with uv (it regenerates the committed file), and take
# the committed THIRD_PARTY_LICENSES.md as authoritative everywhere else.
if ! command -v uv >/dev/null 2>&1; then
  echo "ERROR: license audit requires 'uv' — it is the only environment scoped to this" >&2
  echo "ERROR: project's dependency tree. pip-licenses run under a shared env (e.g. the" >&2
  echo "ERROR: ZGX Nano's 'zgx' conda env) would report hundreds of unrelated packages." >&2
  echo "ERROR: Run this on a machine with uv; THIRD_PARTY_LICENSES.md is committed and" >&2
  echo "ERROR: stays authoritative meanwhile. Refusing to report a pass." >&2
  exit 2
fi
RUNNER=(uv run pip-licenses)

TABLE="$(mktemp)"
CSV="$(mktemp)"
trap 'rm -f "$TABLE" "$CSV"' EXIT

if ! "${RUNNER[@]}" --format=markdown --with-urls --order=license > "$TABLE"; then
  echo "ERROR: pip-licenses failed; THIRD_PARTY_LICENSES.md left unchanged." >&2
  exit 2
fi
if [ ! -s "$TABLE" ]; then
  echo "ERROR: pip-licenses produced no output; THIRD_PARTY_LICENSES.md left unchanged." >&2
  exit 2
fi

cat >> "$TABLE" << 'INNER'

> **Scope note.** This table is generated by `scripts/license_audit.sh` under `uv`, so it
> lists the dependency tree resolved from `uv.lock`. On the HP ZGX Nano the app instead runs
> out of the shared `zgx` conda env, where a few versions differ by design — notably `openai`
> 2.29.0 rather than the locked 3.14.1 (see `docs/DEMO_CENTER_INTEGRATION.md`). The licenses
> are unchanged by those version differences; all are Apache-2.0/MIT/BSD.

## Runtime components not bundled in the app container

| Component | License | Notes |
|---|---|---|
| `Qwen/Qwen3.6-35B-A3B` (model weights, via `unsloth/Qwen3.6-35B-A3B-GGUF`) | Apache-2.0 | Downloaded separately to `~/models/`; not part of the app image |
| `llama.cpp` (`llama-server`) | MIT | Built/installed separately; the app talks to it over HTTP, no linking |
| Ollama (`qwen3.6:35b`) | Ollama MIT; model weights Apache-2.0 | Host service on the ZGX Nano; the app talks to it over HTTP, no linking |
INNER

mv "$TABLE" THIRD_PARTY_LICENSES.md
echo "Wrote THIRD_PARTY_LICENSES.md"

if ! "${RUNNER[@]}" --format=csv > "$CSV"; then
  echo "ERROR: pip-licenses failed on the copyleft scan." >&2
  exit 2
fi
if [ ! -s "$CSV" ]; then
  echo "ERROR: copyleft scan produced no output — not treating that as a pass." >&2
  exit 2
fi

if grep -Ei 'GPL|AGPL|LGPL' "$CSV"; then
  echo "Copyleft dependency found"
  exit 1
else
  echo "License audit OK ($(( $(wc -l < "$CSV") - 1 )) packages audited)"
fi
