# Module-level so every helper below can stay parameterless, but rebindable by
# main() so a second scenario needs no code change. Defaults are the originals, so
# nothing about Harrow Creek moves.
SEED_PATH = REPO_ROOT / "data" / "seeds" / "harrow_creek.yaml"
VAULT_DIR = REPO_ROOT / "data" / "vault"
MANIFEST_PATH = VAULT_DIR / "manifest.json"


def set_scenario(seed_path: Path, vault_dir: Path) -> None:
    global SEED_PATH, VAULT_DIR, MANIFEST_PATH
    # Resolved against REPO_ROOT: manifest entries record paths relative to it, and a
    # relative --vault made that raise rather than write.
    SEED_PATH = seed_path if seed_path.is_absolute() else (REPO_ROOT / seed_path)
    VAULT_DIR = vault_dir if vault_dir.is_absolute() else (REPO_ROOT / vault_dir)
    MANIFEST_PATH = VAULT_DIR / "manifest.json"


def narrative_specs(seed: dict[str, Any]) -> list["NarrativeSpec"]:
    """Document set for this scenario.

    A seed may declare its own `documents:`, which means adding a scenario is a data
    change rather than a code change. Seeds that do not (Harrow Creek) fall back to
    the list this script has always carried.
    """
    declared = seed.get("documents")
    if not declared:
        return NARRATIVE_DOCS
    # A letter is dated by the seed's collaborator list unless the entry says otherwise:
    # left to default, every letter was dated "today", stale 2021 letters included.
    letter_dates = {c["letter_doc"]: c["letter_date"] for c in seed.get("collaborators") or [] if c.get("letter_doc")}
    specs: list[NarrativeSpec] = []
    for entry in declared:
        specs.append(
            NarrativeSpec(
                entry["doc_id"],
                entry["title"],
                tuple(entry.get("word_range", (500, 800))),
                " ".join(str(entry.get("brief", "")).split()),
                entry.get("date") or letter_dates.get(entry["doc_id"]),
            )
        )
    return specs


def load_seed() -> dict[str, Any]:
    return yaml.safe_load(SEED_PATH.read_text(encoding="utf-8"))


def seed_sha256() -> str:
    return hashlib.sha256(SEED_PATH.read_bytes()).hexdigest()


def _round_half_up(value: float) -> int:
    import math

    return int(math.floor(value + 0.5))


@dataclass
class BudgetRow:
    year: int
    category: str
    line_item: str
    amount_usd: int
    fringe_applied: float  # rate applied to compute this line, else 0
    indirect_applied: float  # rate applied to compute this line, else 0
    notes: str


def csv_doc_ids(seed: dict[str, Any]) -> dict[str, str]:
    """Doc ids for the two deterministic CSVs.

    Hardcoded HCCC names meant a second scenario would have written its budget over
    the first one's doc_id. A seed can name them; the defaults keep Harrow Creek's.
    """
    declared = seed.get("csv_documents") or {}
    return {
        "budget": declared.get("budget", "budget-satp-draft"),
        "outcomes": declared.get("outcomes", "prior-outcomes-data"),
    }


def build_budget_rows(seed: dict[str, Any]) -> tuple[list[BudgetRow], dict[str, Any]]:
    """Solve the SATP draft budget so the grand total is exactly
    new_project.budget_total_usd, with fringe = fringe_rate_budget_pct of
    personnel and indirect = rates.indirect_rate_pct of the MTDC base
    (everything except equipment and participant_support). materials_supplies
    is the balancing line, per Spec D.2.
    """
    new_project = seed["new_project"]
    rates = seed["rates"]
    target_total = new_project["budget_total_usd"]
    fringe_rate = new_project["fringe_rate_budget_pct"] / 100.0
    indirect_rate = rates["indirect_rate_pct"] / 100.0

    # Fixed line items by year, chosen to be realistic for a 3-year ATE Track 2 project.
    # (materials_supplies below is a starting point; it is force-corrected at the end.)
    years = [
        {
            "senior_personnel": 95000,
            "other_personnel": 42000,
            "equipment": 72000,
            "travel": 9000,
            "participant_support": 10000,
            "materials_supplies": 10000,
            "evaluation_contract": 18000,
            "other_direct": 6000,
        },
        {
            "senior_personnel": 97850,
            "other_personnel": 43000,
            "equipment": 8000,
            "travel": 9500,
            "participant_support": 12000,
            "materials_supplies": 12000,
            "evaluation_contract": 18000,
            "other_direct": 6000,
        },
        {
            "senior_personnel": 100000,
            "other_personnel": 44000,
            "equipment": 0,
            "travel": 10000,
            "participant_support": 14000,
            "materials_supplies": 14304,
            "evaluation_contract": 19000,
            "other_direct": 6500,
        },
    ]

    rows: list[BudgetRow] = []
    for idx, y in enumerate(years, start=1):
        personnel = y["senior_personnel"] + y["other_personnel"]
        fringe = _round_half_up(fringe_rate * personnel)
        mtdc_base = (
            personnel + fringe + y["travel"] + y["materials_supplies"] + y["evaluation_contract"] + y["other_direct"]
        )
        indirect = _round_half_up(indirect_rate * mtdc_base)

        rows.append(BudgetRow(idx, "senior_personnel", "PI and co-PI effort", y["senior_personnel"], 0, indirect_rate, ""))
        rows.append(BudgetRow(idx, "other_personnel", "Project coordinator / instructional staff", y["other_personnel"], 0, indirect_rate, ""))
        rows.append(BudgetRow(idx, "fringe", "Fringe benefits", fringe, fringe_rate, indirect_rate, f"{fringe_rate:.1%} of personnel"))
        rows.append(BudgetRow(idx, "equipment", "Automation lab equipment", y["equipment"], 0, 0, "excluded from indirect base" if y["equipment"] else "n/a"))
        rows.append(BudgetRow(idx, "travel", "Conference and site-visit travel", y["travel"], 0, indirect_rate, ""))
        rows.append(BudgetRow(idx, "participant_support", "Employer workshop stipends", y["participant_support"], 0, 0, "excluded from indirect base"))
        rows.append(BudgetRow(idx, "materials_supplies", "Instructional materials and supplies", y["materials_supplies"], 0, indirect_rate, "balancing line"))
        evaluator = (seed.get("people", {}).get("evaluator") or {}).get("org", "External evaluator")
        rows.append(BudgetRow(idx, "evaluation_contract", f"{evaluator} contract", y["evaluation_contract"], 0, indirect_rate, ""))
        rows.append(BudgetRow(idx, "other_direct", "Software licenses, dissemination", y["other_direct"], 0, indirect_rate, ""))
        rows.append(BudgetRow(idx, "indirect", "Indirect costs (F&A)", indirect, 0, indirect_rate, f"{indirect_rate:.1%} of MTDC base"))

    grand_total = sum(r.amount_usd for r in rows)
    residual = target_total - grand_total
    if residual != 0:
        # Force-correct: adjust the last year's materials_supplies line, the
        # designated balancing item, without recomputing indirect again.
        for r in reversed(rows):
            if r.category == "materials_supplies":
                r.amount_usd += residual
                break
        grand_total = sum(r.amount_usd for r in rows)

    assert grand_total == target_total, f"budget did not reconcile: {grand_total} != {target_total}"

    # "What if the rate agreement's fringe rate had been used instead" -- for check assertions.
    agreement_fringe_rate = rates["fringe_rate_agreement_pct"] / 100.0
    total_if_agreement_fringe = grand_total
    for idx, y in enumerate(years, start=1):
        personnel = y["senior_personnel"] + y["other_personnel"]
        old_fringe = next(r.amount_usd for r in rows if r.year == idx and r.category == "fringe")
        new_fringe = _round_half_up(agreement_fringe_rate * personnel)
        old_indirect = next(r.amount_usd for r in rows if r.year == idx and r.category == "indirect")
        materials = next(r.amount_usd for r in rows if r.year == idx and r.category == "materials_supplies")
        travel = next(r.amount_usd for r in rows if r.year == idx and r.category == "travel")
        eval_ = next(r.amount_usd for r in rows if r.year == idx and r.category == "evaluation_contract")
        other_direct = next(r.amount_usd for r in rows if r.year == idx and r.category == "other_direct")
        new_mtdc = personnel + new_fringe + travel + materials + eval_ + other_direct
        new_indirect = _round_half_up(indirect_rate * new_mtdc)
        total_if_agreement_fringe += (new_fringe - old_fringe) + (new_indirect - old_indirect)

    summary = {
        "grand_total_usd": grand_total,
        "fringe_rate_used_pct": new_project["fringe_rate_budget_pct"],
        "fringe_rate_agreement_pct": rates["fringe_rate_agreement_pct"],
        "total_if_agreement_fringe_usd": total_if_agreement_fringe,
        "track_cap_usd": 1_000_000,
        "over_cap_by_usd": grand_total - 1_000_000,
    }
    return rows, summary


def write_budget_csv(seed: dict[str, Any]) -> dict[str, Any]:
    buf = io.StringIO()
    writer = csv.writer(buf)
    if seed.get("budget"):
        # The seed declares its own lines (scaled from real comparable awards).
        from app.budget_builder import build as build_declared

        header, declared_rows, summary = build_declared(seed)
        writer.writerow(header)
        for r in declared_rows:
            writer.writerow([r.get(col, "") for col in header])
    else:
        rows, summary = build_budget_rows(seed)
        writer.writerow(["year", "category", "line_item", "amount_usd", "fringe_applied", "indirect_applied", "notes"])
        for r in rows:
            writer.writerow([r.year, r.category, r.line_item, r.amount_usd, r.fringe_applied, r.indirect_applied, r.notes])

    front_matter = {
        "doc_id": csv_doc_ids(seed)["budget"],
        "title": f"{seed['new_project']['short_name']} Draft Budget ({seed['new_project']['years']} years)",
        "doc_type": "csv",
        "date": seed["demo_context"]["today"],
        "synthetic": True,
        "generator": "generate_vault.py",
        "seed_sha256": seed_sha256(),
    }
    path = VAULT_DIR / f"{csv_doc_ids(seed)['budget']}.csv"
    text = "\n".join(f"# {k}: {json_scalar(v)}" for k, v in front_matter.items()) + "\n" + buf.getvalue()
    path.write_text(text, encoding="utf-8")
    if "over_cap_by_usd" in summary:
        print(f"Wrote {path} (grand total ${summary['grand_total_usd']:,}, over cap by ${summary['over_cap_by_usd']:,})")
        print(f"  total_if_agreement_fringe_usd = ${summary['total_if_agreement_fringe_usd']:,}")
    else:
        print(f"Wrote {path} (grand total ${summary['grand_total_usd']:,}, by year {summary['by_year_usd']})")
    return {"doc_id": csv_doc_ids(seed)["budget"], "path": str(path.relative_to(REPO_ROOT)), **front_matter, "summary": summary}


def json_scalar(v: Any) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    return str(v)


def write_generic_outcomes_csv(seed: dict[str, Any]) -> dict[str, Any]:
    """Outcomes as a metric/value table, for a scenario that does not count completers.

    The original builder is shaped entirely around a workforce programme -- enrolled,
    completers, placement respondents. A research institute reports papers, students
    and datasets, so it gets a table of whatever its seed actually records. The keys a
    draft will overstate are written here as the truth for check_claims to catch.
    """
    prior = seed["prior_award"]
    outcomes = prior.get("outcomes") or {}
    ids = csv_doc_ids(seed)

    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(["metric", "value", "notes"])
    for key, value in outcomes.items():
        # "*_claimed_in_draft" records what a proposal will assert, not what happened;
        # writing it into the record of outcomes would defeat the whole check.
        if key.endswith("_claimed_in_draft"):
            continue
        writer.writerow([key.replace("_", " "), value, ""])

    front_matter = {
        "doc_id": ids["outcomes"],
        "title": f"Outcomes Data — {prior.get('title', 'prior award')}",
        "doc_type": "csv",
        "date": seed["demo_context"]["today"],
        "synthetic": True,
        "generator": "generate_vault.py",
        "seed_sha256": seed_sha256(),
    }
    path = VAULT_DIR / f"{ids['outcomes']}.csv"
    text = "\n".join(f"# {k}: {json_scalar(v)}" for k, v in front_matter.items()) + "\n" + buf.getvalue()
    path.write_text(text, encoding="utf-8")
    print(f"Wrote {path} ({len(outcomes)} recorded metrics)")
    return {"doc_id": ids["outcomes"], "path": str(path.relative_to(REPO_ROOT)), **front_matter}


def write_outcomes_csv(seed: dict[str, Any]) -> dict[str, Any]:
    # Scenarios that do not count programme completers get the generic table.
    if "completers_actual" not in (seed.get("prior_award", {}).get("outcomes") or {}):
        return write_generic_outcomes_csv(seed)

    prior = seed["prior_award"]
    completers_by_year = [15, 22, 27, 20]  # sums to 84, matches prior.outcomes.completers_actual
    assert sum(completers_by_year) == prior["outcomes"]["completers_actual"]
    enrolled_by_year = [28, 34, 38, 26]
    program_years = ["2021-22", "2022-23", "2023-24", "2024-25 (no-cost extension)"]

    respondents = prior["outcomes"]["placement_respondents"]
    placement_rate = prior["outcomes"]["placement_rate_pct"] / 100.0
    placed = _round_half_up(placement_rate * respondents)

    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(["year", "enrolled", "completers", "placement_respondents", "placements_employed", "notes"])
    for py, enrolled, completers in zip(program_years, enrolled_by_year, completers_by_year):
        writer.writerow([py, enrolled, completers, "", "", ""])
    writer.writerow(
        [
            "TOTAL",
            sum(enrolled_by_year),
            sum(completers_by_year),
            respondents,
            placed,
            "Placement rate reported over survey respondents, not total completers",
        ]
    )

    front_matter = {
        "doc_id": csv_doc_ids(seed)["outcomes"],
        "title": "Outcomes Data 2021-2025",
        "doc_type": "csv",
        "date": seed["demo_context"]["today"],
        "synthetic": True,
        "generator": "generate_vault.py",
        "seed_sha256": seed_sha256(),
    }
    path = VAULT_DIR / f"{csv_doc_ids(seed)['outcomes']}.csv"
    text = "\n".join(f"# {k}: {json_scalar(v)}" for k, v in front_matter.items()) + "\n" + buf.getvalue()
    path.write_text(text, encoding="utf-8")
    print(f"Wrote {path} (completers: {sum(completers_by_year)}/{prior['outcomes']['completers_target']} target)")
    return {"doc_id": csv_doc_ids(seed)["outcomes"], "path": str(path.relative_to(REPO_ROOT)), **front_matter}


