def _drafter_client():
    from app.llm_client import LLMClient
    from app.settings import load_settings

    settings = load_settings()
    # Offline generation can run longer than the app's live drafter profile allows.
    settings.llm.profiles["drafter"].max_tokens = 3800
    return LLMClient(settings)


def _facts_for_prompt(seed: dict[str, Any]) -> dict[str, Any]:
    """The seed as the drafting model should see it: facts, not the answer key.

    The whole seed used to go in, planted_issues and all, and the model obligingly
    wrote the answers into the documents -- a rate agreement noting that "active
    proposals have incorrectly utilized a fringe rate of 28.0%". Withheld: the planted
    issues and the validator's guards; every other document's brief (they carry
    instructions like "a reviewer is supposed to notice this"); the numbers a draft will
    falsely claim; and the budget's lines, whose flags mark the planted errors. The
    budget is summarised instead.
    """
    hidden = {"planted_issues", "must_not_contain", "key_facts", "documents", "budget"}

    def scrub(value: Any) -> Any:
        if isinstance(value, dict):
            return {k: scrub(v) for k, v in value.items() if not str(k).endswith("_claimed_in_draft")}
        if isinstance(value, list):
            return [scrub(v) for v in value]
        return value

    facts = {k: scrub(v) for k, v in seed.items() if k not in hidden}
    if seed.get("budget"):
        from app.budget_builder import build as build_declared

        summary = build_declared(seed)[2]
        facts["budget_summary"] = {
            "total_requested_usd": summary["grand_total_usd"],
            "requested_by_year_usd": summary["by_year_usd"],
            "fringe_rate_pct": summary["fringe_rate_used_pct"],
            "indirect_rate_pct": summary["indirect_rate_pct"],
        }
    return facts


def generate_narrative_doc(client, seed: dict[str, Any], spec: NarrativeSpec) -> str:
    # Seeds without a declared budget (Harrow Creek) keep the prompt they were built with.
    seed_yaml = yaml.dump(_facts_for_prompt(seed) if seed.get("budget") else seed, sort_keys=False)
    prompt = (
        "You are drafting a synthetic institutional document for a fictional grant-writing software demo.\n"
        f"Institution: {seed['institution']['name']} ({seed['institution']['short_name']})\n\n"
        f"Document to write: {spec.title}\n"
        f"Brief: {spec.brief}\n\n"
        "Use ONLY the facts in the seed data below. Do not invent any number, name, date, or outcome that "
        "contradicts it, but you may invent plausible fictional names/details not covered by the seed data "
        "(e.g. advisory board members, signatories) as instructed in the brief.\n\n"
        f"Seed data:\n{seed_yaml}\n"
        f"Write {spec.word_range[0]}-{spec.word_range[1]} words of professional grant-document prose. "
        "Do not include a top-level title heading (front matter supplies the title) -- start directly with the "
        "body, using ## subheadings where natural. Return only the document body in Markdown."
    )
    result = client.chat("drafter", [{"role": "user", "content": prompt}], stream=True)
    return result.content.strip()


def write_narrative_doc(seed: dict[str, Any], spec: NarrativeSpec, body: str) -> dict[str, Any]:
    front_matter = {
        "doc_id": spec.doc_id,
        "title": spec.title,
        "doc_type": "md",
        "date": spec.date or seed["demo_context"]["today"],
        "synthetic": True,
        "generator": "generate_vault.py",
        "seed_sha256": seed_sha256(),
    }
    fm_text = yaml.safe_dump(front_matter, sort_keys=False, default_flow_style=False, allow_unicode=True)
    text = f"---\n{fm_text}---\n{body}\n"
    path = VAULT_DIR / f"{spec.doc_id}.md"
    path.write_text(text, encoding="utf-8")
    word_count = len(body.split())
    print(f"Wrote {path} ({word_count} words, target {spec.word_range[0]}-{spec.word_range[1]})")
    return {"doc_id": spec.doc_id, "path": str(path.relative_to(REPO_ROOT)), **front_matter}


def update_manifest(entries: list[dict[str, Any]]) -> None:
    manifest: dict[str, Any] = {}
    if MANIFEST_PATH.exists():
        manifest = __import__("json").loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    docs = {d["doc_id"]: d for d in manifest.get("documents", [])}
    for e in entries:
        docs[e["doc_id"]] = {k: v for k, v in e.items() if k != "summary"}
    manifest["documents"] = list(docs.values())
    MANIFEST_PATH.write_text(__import__("json").dumps(manifest, indent=2, sort_keys=False) + "\n", encoding="utf-8")
    print(f"Updated {MANIFEST_PATH} ({len(manifest['documents'])} documents)")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seed", help="path to a scenario seed (default: harrow_creek.yaml)")
    parser.add_argument("--vault", help="output directory (default: data/vault)")
    parser.add_argument("--only", help="regenerate a single doc_id")
    parser.add_argument("--force", action="store_true", help="regenerate all documents")
    parser.add_argument("--csv-only", action="store_true", help="generate only the deterministic CSV documents")
    args = parser.parse_args()

    if args.seed or args.vault:
        seed_path = Path(args.seed) if args.seed else SEED_PATH
        vault_dir = Path(args.vault) if args.vault else (REPO_ROOT / "data" / "scenarios" / seed_path.stem)
        set_scenario(seed_path, vault_dir)
        print(f"Scenario: {seed_path.name} -> {vault_dir}")

    VAULT_DIR.mkdir(parents=True, exist_ok=True)
    seed = load_seed()
    specs = narrative_specs(seed)

    entries: list[dict[str, Any]] = []

    csv_generators = {
        "budget-satp-draft": write_budget_csv,
        "prior-outcomes-data": write_outcomes_csv,
    }
    for doc_id, fn in csv_generators.items():
        if args.only and args.only != doc_id:
            continue
        entries.append(fn(seed))

    if args.csv_only:
        update_manifest(entries)
        print("CSV-only run complete. Run again without --csv-only once the model server is up "
              "to generate the narrative (md) documents.")
        return 0

    if args.only and args.only in csv_generators:
        update_manifest(entries)
        return 0

    client = _drafter_client()
    for spec in specs:
        if args.only and args.only != spec.doc_id:
            continue
        dest = VAULT_DIR / f"{spec.doc_id}.md"
        if dest.exists() and not args.force and not args.only:
            print(f"Skipping {spec.doc_id} (already exists; use --force or --only to regenerate)")
            continue
        print(f"Generating {spec.doc_id} ...")
        body = generate_narrative_doc(client, seed, spec)
        entries.append(write_narrative_doc(seed, spec, body))

    update_manifest(entries)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
