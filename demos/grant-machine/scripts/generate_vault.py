"""Phase 4.4: generate the synthetic institutional vault (Spec D.2).

Tabular documents (csv) are generated deterministically from the seed file,
no LLM involved. Narrative documents (md) are generated by the local model
with the drafter profile and require a running model server.

Usage:
    uv run python scripts/generate_vault.py              # generate everything
    uv run python scripts/generate_vault.py --csv-only    # just the two CSVs (no model needed)
    uv run python scripts/generate_vault.py --only budget-satp-draft
    uv run python scripts/generate_vault.py --force
"""

