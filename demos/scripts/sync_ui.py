#!/usr/bin/env python3
"""Inject the shared ZGX chrome into every demo frontend.

Everything is inlined -- stylesheet, script, and the HP logo as a data URI.
That is deliberate. The demos are served by different processes, several from
inside containers with their own static roots and no route back to the
launcher, and two of them rewrite their own HTML with `sed` on every launch. A
single self-contained block has no path to resolve, no extra file to serve, no
CORS, and nothing to go stale in an image built last month.

Titles come from install_plans.py, so the chrome cannot drift from the names
the launcher shows.

Idempotent: re-running replaces the block between the markers.

    python3 scripts/sync_ui.py            # all demos with a known frontend
    python3 scripts/sync_ui.py --check    # verify only, exit 1 if out of date
    python3 scripts/sync_ui.py ballistics # one demo
"""

from __future__ import annotations

import base64
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import install_plans  # noqa: E402

BEGIN = "<!-- zgx-ui:begin (generated by scripts/sync_ui.py — edit demos/ui/, not this) -->"
END = "<!-- zgx-ui:end -->"

# Where each demo's presenter-facing HTML lives, and a subtitle for the bar.
# Robotic-medical is absent by the same scope decision as everywhere else.
FRONTENDS = {
    "ballistics":   ("ballistics-containerized-docker/frontend/index.html", "Defense / Range Surveillance"),
    "pii":          ("pii-demo-containerized-docker/frontend/index.html", "Security / Data Privacy"),
    "pharmacy":     ("healthcare-pharmacy-containerized-docker/frontend/index.html", "Healthcare / Clinical"),
    "maritime":     ("Fed-Navy-containerized-docker/frontend/index.html", "Defense / Navy"),
    "construction": ("AEC-construction-safety/frontend/index.html", "AEC / Site Safety"),
    "translation":  ("document-translation/frontend/index.html", "Enterprise / Localization"),
    "spectrum":     ("ew-spectrum-duel/ew_demo.html", "Defense / Electronic Warfare"),
    "pipeline":     ("pipeline-pulse/pipeline_pulse_v6.html", "Energy / Industrial Monitoring"),
    "grant":        ("grant-machine/web/index.html", "Public Sector / Research Funding"),
    "vehicle":      ("automotive-vehicle-inspection/frontend/index.html", "Automotive / Port Logistics"),
}


def build_block(demo_id: str, title: str, subtitle: str) -> str:
    css = (ROOT / "ui" / "zgx-ui.css").read_text(encoding="utf-8")
    js = (ROOT / "ui" / "zgx-ui.js").read_text(encoding="utf-8")
    logo = base64.b64encode((ROOT / "ui" / "brand" / "hp_logo.png").read_bytes()).decode("ascii")
    esc = lambda t: t.replace("&", "&amp;").replace('"', "&quot;").replace("<", "&lt;")
    return (
        f"{BEGIN}\n"
        f"<style>\n{css}</style>\n"
        f'<div id="zgx-chrome" data-demo="{esc(demo_id)}" data-title="{esc(title)}"'
        f' data-subtitle="{esc(subtitle)}" data-logo="data:image/png;base64,{logo}"></div>\n'
        f"<script>\n{js}</script>\n"
        f"{END}\n"
    )


def sync(demo_id: str, check: bool) -> bool:
    if demo_id not in FRONTENDS:
        print(f"  !! unknown demo: {demo_id}")
        return False
    rel, subtitle = FRONTENDS[demo_id]
    target = ROOT / rel
    if not target.is_file():
        print(f"  skip {demo_id}: {rel} not found")
        return True

    plan = install_plans.INSTALL_PLANS.get(demo_id, {})
    title = plan.get("name", demo_id)
    block = build_block(demo_id, title, subtitle)

    html = target.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", re.S)

    if pattern.search(html):
        updated = pattern.sub(lambda _m: block, html)
    elif "</body>" in html:
        updated = html.replace("</body>", block + "</body>", 1)
    else:
        updated = html + "\n" + block

    if updated == html:
        print(f"  ok   {demo_id} (current)")
        return True
    if check:
        print(f"  STALE {demo_id}: {rel}")
        return False
    target.write_text(updated, encoding="utf-8")
    print(f"  sync {demo_id} -> {rel}")
    return True


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    check = "--check" in sys.argv
    targets = args or list(FRONTENDS)
    print("== zgx-ui " + ("check" if check else "sync") + " ==")
    ok = all(sync(d, check) for d in targets)
    if not ok and check:
        print("\nRun: python3 scripts/sync_ui.py")
        return 1
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
