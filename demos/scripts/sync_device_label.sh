#!/usr/bin/env bash
# Inline scripts/zgx-device-label.js into every demo frontend, between markers.
#
# The demos are served by different processes (some containerised with their own
# static roots), so a shared <script src> would have to be reachable from all of
# them. Inlining a ~20-line snippet is the boring option that works everywhere,
# including offline and inside a container with no network route to the launcher.
#
# Idempotent: re-running replaces the block between the markers.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
snippet="$here/zgx-device-label.js"
[ -f "$snippet" ] || { echo "missing $snippet" >&2; exit 1; }

BEGIN="<!-- zgx-device-label:begin (generated by scripts/sync_device_label.sh) -->"
END="<!-- zgx-device-label:end -->"

for f in "$@"; do
  [ -f "$f" ] || { echo "skip (missing): $f"; continue; }
  python3 - "$f" "$snippet" "$BEGIN" "$END" <<'PY'
import pathlib, re, sys
target, snip, begin, end = sys.argv[1:5]
html = pathlib.Path(target).read_text(encoding="utf-8")
block = f'{begin}\n<script>\n{pathlib.Path(snip).read_text(encoding="utf-8")}</script>\n{end}\n'
pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end) + r"\n?", re.S)
if pattern.search(html):
    html = pattern.sub(block, html)
elif "</body>" in html:
    html = html.replace("</body>", block + "</body>", 1)
else:
    html += "\n" + block
pathlib.Path(target).write_text(html, encoding="utf-8")
print(f"  synced {target}")
PY
done
