"""Token accounting shared by every demo that calls an LLM.

Two server shapes, one answer:

  Ollama native (/api/generate, /api/chat)
      prompt_eval_count, eval_count, eval_duration, prompt_eval_duration (ns)
  OpenAI-compatible (/v1/chat/completions)
      usage.prompt_tokens, usage.completion_tokens

Where Ollama reports durations we use them: eval_count / (eval_duration / 1e9)
is a TRUE decode rate. grant-machine's equivalent divides by wall-clock time for
the whole call including prompt processing, a simplification its own PROGRESS.md
records at line 334. Prefer the better number when the server hands it over.

`estimated` is sticky and surfaces in the UI as a leading "≈". It is set when a
server returned no counts at all and the figure is a character heuristic. A
demo's token meter has exactly one job -- to be the real number of tokens this
machine processed -- so when it cannot be, it says so.

CANONICAL COPY: demos/zgx_metrics.py. The copies under each demo's backend/ are
generated by scripts/sync_metrics.py because containerised demos only COPY
backend/ and frontend/ into their image, putting this file outside their build
context. Run `python3 scripts/sync_metrics.py --check` to prove they agree.
"""

from __future__ import annotations

import math
import threading


def _estimate_tokens(text: str) -> int:
    """Character heuristic, used only when a server reports nothing at all."""
    return math.ceil(len(text) / 3.5) if text else 0


def normalize(raw: dict | None, *, fallback_text: str = "", wall_s: float | None = None) -> dict:
    """One LLM call's usage, from either server shape. Never raises.

    Returns {prompt, completion, total, tps, estimated}. `tps` is None rather
    than 0.0 when it cannot be computed -- 0 tok/s is a reading, absence is not.
    """
    raw = raw or {}
    prompt = completion = None
    tps = None
    estimated = False

    usage = raw.get("usage")
    if isinstance(usage, dict):                       # OpenAI-compatible
        prompt = usage.get("prompt_tokens")
        completion = usage.get("completion_tokens")
    if prompt is None and "prompt_eval_count" in raw:  # Ollama native
        prompt = raw.get("prompt_eval_count")
    if completion is None and "eval_count" in raw:
        completion = raw.get("eval_count")

    # Ollama's own decode duration, in nanoseconds — a true rate.
    eval_ns = raw.get("eval_duration")
    try:
        if completion and isinstance(eval_ns, (int, float)) and eval_ns > 0:
            tps = completion / (eval_ns / 1e9)
        elif completion and wall_s and wall_s > 0:
            tps = completion / wall_s
    except (TypeError, ValueError, ZeroDivisionError):
        tps = None

    if prompt is None and completion is None:
        completion = _estimate_tokens(fallback_text)
        prompt = 0
        estimated = True
        if completion and wall_s and wall_s > 0:
            tps = completion / wall_s

    # Coerced defensively: a server that returns a non-numeric count would
    # otherwise raise ValueError out of int(), from inside the request path of
    # whichever demo made the call. Token accounting must never be able to fail
    # a request -- it is a readout, not part of the work.
    def _int(v):
        try:
            return int(v)
        except (TypeError, ValueError):
            return 0

    prompt = _int(prompt)
    completion = _int(completion)
    return {
        "prompt": prompt,
        "completion": completion,
        "total": prompt + completion,
        "tps": round(tps, 1) if tps else None,
        "estimated": estimated,
    }


class TokenLedger:
    """Session totals. Thread-safe; every demo here is concurrent somewhere."""

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._prompt = 0
        self._completion = 0
        self._requests = 0
        self._estimated = False
        self._last_tps: float | None = None

    def record(self, raw: dict | None, *, fallback_text: str = "", wall_s: float | None = None) -> dict:
        """Add one call and return its normalized usage."""
        one = normalize(raw, fallback_text=fallback_text, wall_s=wall_s)
        with self._lock:
            self._prompt += one["prompt"]
            self._completion += one["completion"]
            self._requests += 1
            # Sticky: one estimated call taints the session total, so the UI's
            # "≈" stays on rather than implying the whole figure was measured.
            self._estimated = self._estimated or one["estimated"]
            if one["tps"]:
                self._last_tps = one["tps"]
        return one

    def snapshot(self) -> dict:
        """The /api/metrics payload the shared chrome expects."""
        with self._lock:
            return {
                "prompt_tokens": self._prompt,
                "completion_tokens": self._completion,
                "total_tokens": self._prompt + self._completion,
                "requests": self._requests,
                "tps": self._last_tps,
                "estimated": self._estimated,
            }

    def reset(self) -> None:
        with self._lock:
            self._prompt = self._completion = self._requests = 0
            self._estimated = False
            self._last_tps = None
